def normalize_ui_language(value: object) -> str:
    code = str(value or "").casefold().replace("_", "-").split("-", 1)[0]
    return code if code in SUPPORTED_UI_LANGUAGES else "en"


def ui_text(key: str, language: str, **values: object) -> str:
    locale = normalize_ui_language(language)
    template = CATALOGS.get(locale, _EN).get(key, _EN.get(key, key))
    return template.format(**values)


def source_language_name(code: str, language: str) -> str:
    locale = normalize_ui_language(language)
    return SOURCE_LANGUAGE_NAMES.get(locale, SOURCE_LANGUAGE_NAMES["en"]).get(code, code)


def job_term(key: str, language: str) -> str:
    locale = normalize_ui_language(language)
    return JOB_TERMS.get(locale, JOB_TERMS["en"]).get(key, key)


def validate_catalogs() -> tuple[str, ...]:
    expected = set(_EN)
    errors: list[str] = []
    missing_catalogs = sorted(set(SUPPORTED_UI_LANGUAGES) - set(CATALOGS))
    extra_catalogs = sorted(set(CATALOGS) - set(SUPPORTED_UI_LANGUAGES))
    if missing_catalogs:
        errors.append(f"missing catalogs: {', '.join(missing_catalogs)}")
    if extra_catalogs:
        errors.append(f"unsupported catalogs: {', '.join(extra_catalogs)}")
    for language in SUPPORTED_UI_LANGUAGES:
        catalog = CATALOGS.get(language)
        if catalog is None:
            continue
        missing = sorted(expected - set(catalog))
        extra = sorted(set(catalog) - expected)
        if missing:
            errors.append(f"{language}: missing {', '.join(missing)}")
        if extra:
            errors.append(f"{language}: extra {', '.join(extra)}")
        for key in sorted(expected & set(catalog)):
            expected_fields = {
                name for _, name, _, _ in Formatter().parse(_EN[key]) if name is not None
            }
            actual_fields = {
                name
                for _, name, _, _ in Formatter().parse(catalog[key])
                if name is not None
            }
            if actual_fields != expected_fields:
                errors.append(
                    f"{language}: placeholders for {key}: "
                    f"expected {sorted(expected_fields)}, got {sorted(actual_fields)}"
                )
    for label, localized, reference in (
        ("source language names", SOURCE_LANGUAGE_NAMES, SOURCE_LANGUAGE_NAMES["en"]),
        ("job terms", JOB_TERMS, JOB_TERMS["en"]),
    ):
        expected_terms = set(reference)
        for language in SUPPORTED_UI_LANGUAGES:
            terms = localized.get(language)
            if terms is None:
                errors.append(f"{language}: missing {label}")
                continue
            missing = sorted(expected_terms - set(terms))
            extra = sorted(set(terms) - expected_terms)
            if missing:
                errors.append(f"{language}: missing {label}: {', '.join(missing)}")
            if extra:
                errors.append(f"{language}: extra {label}: {', '.join(extra)}")
    return tuple(errors)
